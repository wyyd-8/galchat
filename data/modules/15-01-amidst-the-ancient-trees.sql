#### 第3天：藏身处

空地中间有一座老旧的木屋。屋子的门关着，看不出有人活动的迹象。

当调查员走入空地中时，他们会嗅到死亡的气味。这股恶臭来自一棵浸满鲜血的树，一个人被树枝穿胸而过挂在半空--正是克里斯托弗•多布斯，留下看守女孩的那个绑匪。调查员需要进行理智检定，由于死状过于恐怖，调查员将损失0/1D4点理智值。

木屋上布满了穿透的弹孔。如果进一步调查的话，会发现这些子弹都是从屋里射出去的。

调查员可能会被发现的尸体分散了注意力，而没能注意到哈里斯还活着躲在木屋里。当哈里斯听见调查员靠近的时候，他会从木屋里用霰弹枪开火（需要注意的是霰弹枪的伤害随距离递减，并且无法造成贯穿伤害）。他会大喊：“要么把她还回来，要么就给我滚！”他因格拉基的梦唤而陷入疯狂，夜里一直在抵挡不死仆从的攻击。除非调查员能够制伏他或是让他冷静下来（极限说服、取悦或恐吓检定），否则他就会不停开枪，唯恐调查员也是前来抓走他的恐怖怪物。

如果调查员成功让哈里斯平静下来，他会交代女孩已经不见了。他前一天晚上发现多布斯死了，当天夜里就遭到了（仆从的）攻击。说完这些之后，他就会彻底崩溃，陷入歇斯底里。

#### 第3天：特纳的小屋

搜查队回过头来追寻森林中的踪迹的话，会发现这些踪迹分成了两个方向。一条路看起来最近有人走过，另一条路则没什么人走的痕迹。森林的地面上铺满了新落下的树叶，这是秋天才应该出现的景象。经历过梦唤材料“穿过森林的小径”的人会意识到这条鲜有人迹的小路曾经出现在自己的梦里（理智检定，损失0/1点理智值）。如果他们沿着那条最近有人走过的路向前走，那么前往第3天：挖掘现场（见第358页）。

如果他们沿着那条老旧而少有人走的路前进，他们会看到左边有一片空地，那里有一座更加古旧的小木屋：特纳的小屋。经历过梦唤材料“黑暗中的小屋”的人会立刻认出这正是他们梦中的小屋（理智检定，损失1/1D6点理智值，因为梦境带来的恐惧又在他们的脑海中重现了）。这条路经过这片空地继续向前延伸，通往第3天：湖畔（见第358页）。

小屋里，墙上挂着南北战争时期联邦军的制服和帽子，桌子上放着血迹斑斑的猎刀，天花板上垂下的钩子上挂着死去已久的动物。这里没有生火做饭的痕迹。墙角处立着一把南北战争时期的老式步枪。这把枪看起来没有经过保养；它的零件都已经锈死卡住了。

侦查检定会让调查员发现有浅蓝色的光从地板的缝隙间透露而出。调查员可以找到一扇活板门，通向下方一间土砌成的地下室。浅蓝色的光是五副蓝色的石棺散发出来的，不死仆从白天于此成眠以避免阳光对自己造成伤害（他们也可以在其他地方避光，但他们更喜欢这些石棺）。这些石棺是神明赐予仆从的礼物。

