#### 第3天：湖畔

跟随着老旧的那条路继续向前，就会抵达调查员梦中见过的那片漆黑的死水湖。幸存的五名画家都被绑在距离湖岸约五米远的柱子上。第2天傍晚他们被带到这里献祭给了格拉基，格拉基从湖中升起，在每个人胸前插了一根60厘米（两英尺）长、具有金属质感的脊刺；可怜的画家们身上溅满了血肉内脏。调查员需要进行理智检定，理智损失1/1D6。画家们理应都已死去，但如果调查员走得足够近，他们会发现这些画家却仍在活动--这会让他们进行第二次理智检定，理智损失1/1D4。

尽管他们的精神已经被经历的事情摧毁，但如果调查员把他们放下来，他们还是能够讲述自己的遭遇。朗读或转述下面的内容：

> “他们夜里把我们从营地里抓走了……活尸……他们把我们带到了挖掘现场，其他人被关在那里。有一个男孩，一个男人，还有一个女孩。我们中有个人逃走了……活尸打算把什么东西从一个坑里抬出来。他们用上了各种工具，还有炸药。水里有恐怖的东西。他在我们体内，像疾病一样蔓延。我能感受到它在燃烧我的灵魂。杀了我们吧！把这根刺拔出来！求求你了！”

把脊刺从他们的胸前拔出来就能结束他们的痛苦，他们会依次尖叫着死去，而尖叫声很可能会引起仆从们的注意。调查员需要进行团体幸运检定。如果检定失败，詹姆斯•斯坦顿和迪恩•沃尔特斯就会从附近的挖掘现场赶来查看情况。

如果调查员留下来观察会发生什么，他们需要进行潜行检定以避免被发现。如果不死仆从发现调查员，他们就会试图制伏调查员，将其带到棚屋去（见第360页，俘虏调查员）。如果调查员把脊刺从俘虏身上拔下来，仆从就会毫不在意地丢弃那些尸体，将被俘虏的调查员绑到柱子上去。挣脱束缚需要进行困难力量或敏捷检定。如果检定失败，玩家可以孤注一掷。记住，玩家必须让孤注一掷合理化。孤注一掷失败的结果可能是调查员摇晃柱子太厉害以至于柱子翻倒了，调查员脸朝下栽倒在水里。或者调查员晕过去了，在夜里格拉基出现的时候才醒过来。

如果夜幕降临时他们还被绑在柱子上，特纳一伙就会来到湖边召唤格拉基，把调查员作为不死仆从献祭给他。如果画家没有在调查员帮助下获得解脱，他们午夜时分就会变成新的不死仆从。

#### 第3天：挖掘现场

这一场景如何展开取决于调查员的行动；要看他们是盲目地闯入挖掘现场，还是采取了更谨慎的方式（见第361页，更谨慎的做法）。

##### 光明正大地进入挖掘现场

顺着路向前走，调查员会听到前方传来一阵喧闹。转过一个弯后，他们会看到勘探队的一名不死仆从理查德•吉布森守在一道拦路的五杆门旁。道路一直延伸至视野之外，但调查员能看到几间棚屋和一片空地，空地上还传来了机器的声音。

