所有进行聆听检定的人也可以尝试进行侦查检定。检定成功的调查员会看到前面的路上有两个人，手里拿着步枪。聆听检定失败的人则需要进行困难侦查检定（结果小于等于技能半值才视作成功）。两人是一名男子和一名男孩，都拿着步枪，背着背包。

即使没有人看见或是听见猎人们靠近，调查员也会通过前方传来的枪声意识到他们的存在。如果有调查员穿着颜色鲜艳的衣服，那就不会有枪声，因为猎人不会把他们错认成猎物。男子和男孩会走上前来，以更友好的方式出现。

