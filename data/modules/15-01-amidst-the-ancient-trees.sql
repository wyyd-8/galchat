##### 挖掘现场内部

挖掘现场的空地边缘有五间临时搭建的棚屋。空地中央炸出了一个大坑，通向水晶所处的坑洞。

詹姆斯•斯坦顿、迪恩•沃尔特斯和卡尔•怀特不断在坑洞和最远处的棚屋（工具间）之间来回往返，正在用绳子和其他工具把水晶拖到地面上来。到了夜里，特纳和他的手下也会前来帮忙。

第一间棚屋是领班的办公室。这里挂着森林的地质勘探地图，上面很多地点都有标记（疑似矿藏所在地），屋里还放着很多基础的实验器材。如果调查员有机会翻阅这里的文件，他们会发现这里某些特定的矿藏无法分析出成分，勘探队被派来就是为了寻找排干水后盆地区域内的所有矿藏，以免造成水库污染。

五间棚屋中的第二间是勘探队住宿的地方，还放着他们携带的极少量必备品。

第三间棚屋被用作厨房兼杂物间（最近没有使用过）。

第四间棚屋的窗户用木板封死了，门牌上简单地写着“储藏室”。这是关押俘虏的地方。

在远处尽头的第五间棚屋，门牌上写着“工具间”。这里放着钻机和其他工具，例如炸药。

##### 卡尔的解释与圈套

如果调查员获准进入挖掘现场，他们会被介绍给卡尔•怀特。卡尔起初对调查员非常友好，邀请他们去他办公室坐坐。由于卡尔和他的队员们刚刚被转化成格拉基之仆，他们还不会受到日光照射的伤害，不过在酷暑难耐的夏日，还是阴凉的地方更适合长谈。

