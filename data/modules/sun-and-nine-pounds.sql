然而，他没有料到，自己对神秘学的防范反而引起他年幼的儿子——乔治·霍西对书房那片神秘天地的兴趣。在偷偷进入书房后，乔治对这些未知的事物着迷，神秘学对他的童年造成了巨大的影响。神秘学伴随乔治长大，并令其鄙视科学，认为人类的力量永远无法战胜神秘和未知。

迈德发现时已经晚了，他规劝乔治，但效果甚微。父子二人的观点随着年龄增长而逐渐产生冲突，幸运的是这并没有过多影响父子之间的关系。在乔治成人后，迈德退休并将银行的股份交给儿子，然后开始关注伦敦皇家学会的最新科学进展，并不断为其投资，但大部分投资都打了水漂。

乔治的妻子因难产去世，只剩乔治一人同迈德抚养刚出世的女儿。1875年，乔治因为参与反对工业的环保游行被骑警冲撞，受了重伤。迈德打算将儿子送往格拉斯哥皇家医院接受约瑟夫·李斯特医生的手术，但此举遭到了乔治的强烈反对。乔治坚决认为手术只会害死自己，宁愿去找巫师来为自己治疗也不肯接受手术。与此同时，迈德听信他人的宣传，偷偷挪用家族的流动资产投资某个科学产品，导致筹集乔治的手术费用时，迈德不得不替乔治做决定，将银行的股份低价出售。

手术最终失败了，乔治死了，留下迈德和3岁的女儿莉斯伊尔。迈德遭到了巨大的打击，将儿子的死归咎于自己。此时，他投资的科学产品传来消息称，发明人携款跑路，他的投资全部打了水漂。而由于乔治的死亡和银行股份的出售，他创立的伊拉索尔银行被戴维斯子爵收购。

接二连三的打击和丧子之痛使这个年迈的老人一蹶不振，他将最后的希望放在他亲手参与捣毁的邪教徒使用的‘万应灵药’上，据邪教徒说这个药剂能实现人的所有愿望。

