“卫生观念”最早出现于19世纪初的巴黎。随后，在维多利亚时期早期，在英国最有影响力的人物——埃德温·查德威克(Edwin Chadwick，1800—1890)的推动下，这一观念得到了更系统的发展。

在现代微生物理论普及之前，所谓的瘴气理论曾经风行一时，包括疾病是由病菌传播的理论也无法与之匹敌。即便在19世纪晚期，有关疾病成因的瘴气说仍大有市场，一些著名的公共卫生改革者也为之竭力辩护。他们坚称，恶劣的卫生状况、污秽和有害气体引发了流行病，并在欧洲迅速发展的城市蔓延开来。

为了证明在伦敦饮用水中发现的污染物，查德威克调查了大量含垃圾、污物和微生物的水样本。他得出结论，由污染和污物造成的疾病，比英国的任何战争都多。

1842年，查德威克出版《关于英国劳动人口卫生状况的报告》（简称《卫生报告》）。这份报告是现代公共卫生的基础文献之一，报告详细描写了工人们肮脏恐怖的生活条件。并在这之后，查德威克与索思伍德·史密斯在1843年建立了一个城镇卫生委员会。1848年，查德威克推动政府通过了具有里程碑意义的《公共卫生法案》。

查德威克通过一系列的方式令人们和社会认识到，环境污染会导致疾病，但是对于具体感染的原因则还是以瘴气论为主。

而英国内科医生约翰·斯诺（John Snow）对1854年伦敦霍乱的研究则反对这一观点。他认为霍乱的具体原因是通过口腔进入消化系统的，随后，霍乱患者的排泄物通过水传染给了新的受害者。

