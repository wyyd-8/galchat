**感染初期**：蠕虫进入患者的消化系统，并开始繁殖。患者会感觉身体虚弱，四肢无力，喉咙发痒并伴随着时不时的干呕，排泄物中有白色蠕虫，看起来像是长着白毛。

**感染中期**：蠕虫在消化系统内大量繁殖，形成族群，开始替代患者的体液、血肉和身体器官。患者腹部发白，出现恶心、干呕、剧烈咳嗽，甚至咯血等症状。咳出来的血液偏白色，主要由细小的蠕虫构成。患者的排泄物呈白色。由于体内有蠕虫，患者开始散发出一种腐臭味。

**感染晚期**：蠕虫完全替代患者的体液，患者血管呈白色。蠕虫完全占据患者的消化系统，患者腹部由于细胞破裂、组织液堆积而呈白色，在受到外力刺激后，患者皮肤破裂，并有数量可观的白色蠕虫钻出。患者浑身散发着恶臭，光是闻到气味就已经让人反胃。

**感染末期**：蠕虫完全占据患者的躯体，此时患者的神志已经模糊。肉眼可以观察到白色蠕虫从毛孔中向外伸展。患者的瞳孔变为白色，里面有白色蠕虫蜿蜒蠕动。患者身体虽然依然保持活性，但已经可以宣布死亡了。

**转化的蠕行者**：患者的大脑被蠕虫吞噬并且占据。吞噬大脑的蠕虫将患者的灵魂和记忆转移到自己身上，并共享给全身上下的每只蠕虫。蠕臭症患者正通过莉斯伊尔身上繁殖出来的蠕虫慢慢转变成蠕行者，但他们与真实的蠕行者相比有更多缺陷。

