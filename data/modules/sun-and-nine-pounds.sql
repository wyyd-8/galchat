### 调查员的感染进度

调查员在模组中，有可能会被蠕臭症感染，而感染条件则是这些白色的蠕虫进入调查员的身体可，那么调查员就有可能被感染。在初次感染时，调查员需要通过一个体质检定，失败的结果是调查员将感染蠕臭症，调查员的感染进度为0。感染了蠕臭症的调查员会出现一些症状，从而影响行动。以下是参考范例：

1. 调查员突然干呕，发现呕吐物中掺杂着细小的白色蠕虫。

2. 调查员感觉胃肠中有什么东西在蠕动，一种瘙痒的感觉遍布调查员的腹部。

