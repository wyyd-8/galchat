### 故事背景

迈德·霍西是一名退休的银行家。1875年，因为各种原因，他失去了自己唯一的儿子——乔治·霍西。丧子的痛苦加上其他打击让这个老人陷入疯魔，沉迷神秘学当中，寻找复活儿子的办法。而他最后找到的方法是一份名为‘万应灵药’的配方。

为此，他几乎变卖了所有家产，辞退了仆人，并在1880年辞退了仅剩的管家，卖掉了自己的别墅，住进了维根市的贫民窟——薰衣草街区。这在当时的维根市引起了轰动，所有人都把这起丑闻当做笑料。适逢维根市的市长任期将至，当时的市长担心此事影响到自己的政绩，索性拜托戴维斯子爵压下了这起丑闻。

迈德就这样在贫民窟生活着，他专注于自己的事业。1888年，迈德16岁的孙女——莉斯伊尔·霍西在使用残缺的‘蠕行者唤醒’法术时，导致自己身体出现了问题。在医院中，爱德华医生对这起病例感到惊奇，安慰完迈德后。爱德华向迈德提出请求，愿意用九英镑的价格收购莉斯伊尔的尸体用于解剖研究这起怪病。

迈德毫不犹豫的答应了爱德华，并决定过不久就自己动手杀死莉斯伊尔。这一切都被在病床上装晕的莉斯伊尔听到了。

1888年11月8日，迈德将莉斯伊尔带到地下室，计划用匕首亲手将其杀死，作为祭品酿造万应灵药。然而，这一切都在莉斯伊尔的谋划中，她提前在地下室内布置好了‘蠕行者唤醒’法术要求的法阵。

