    public static String code(int typeRoll, Integer detailRoll) {
        if (typeRoll >= 1 && typeRoll <= 8) {
            if (detailRoll != null) {
                throw new IllegalArgumentException("该疯狂类型不应包含明细骰");
            }
            return Integer.toString(typeRoll);
        }
        if (typeRoll == 9 || typeRoll == 10) {
            requireDetailRoll(detailRoll);
            return typeRoll + ":" + String.format(Locale.ROOT, "%03d", detailRoll);
        }
        throw new IllegalArgumentException("疯狂类型骰必须为1到10");
    }

    public static String display(String code) {
        if (code == null || code.isBlank()) {
            throw new IllegalArgumentException("疯狂编号不能为空");
        }
        if (code.length() == 1 && code.charAt(0) >= '1' && code.charAt(0) <= '8') {
            return SUMMARY_SYMPTOMS.get(code.charAt(0) - '0');
        }
        if (code.matches("(9|10):\\d{3}")) {
            int separator = code.indexOf(':');
            int type = Integer.parseInt(code.substring(0, separator));
            int detail = Integer.parseInt(code.substring(separator + 1));
            requireDetailRoll(detail);
            String description = trimTerminalFullStop((type == 9 ? PHOBIAS : MANIAS).get(detail));
            return (type == 9 ? "恐惧症" : "躁狂症") + "（" + description + "）";
        }
        throw new IllegalArgumentException("无效的疯狂编号：" + code);
    }

    private static void requireDetailRoll(Integer detailRoll) {
        if (detailRoll == null || detailRoll < 1 || detailRoll > 100) {
            throw new IllegalArgumentException("疯狂明细骰必须为1到100");
        }
    }

    private static String trimTerminalFullStop(String description) {
        return description.endsWith("。")
                ? description.substring(0, description.length() - 1)
                : description;
    }

    private static Map<Integer, String> parseTable(String source) {
        Map<Integer, String> entries = new LinkedHashMap<>();
        source.lines().filter(line -> !line.isBlank()).forEach(line -> {
            String[] cells = line.split("\\|", -1);
            for (int index = 1; index + 1 < cells.length; index += 2) {
                String number = cells[index].trim();
                String description = cells[index + 1].trim();
                if (number.isEmpty()) {
                    continue;
                }
                int key = Integer.parseInt(number);
                if (entries.putIfAbsent(key, description) != null) {
                    throw new IllegalStateException("重复的疯狂目录编号：" + key);
                }
            }
        });
        return Collections.unmodifiableMap(entries);
    }
